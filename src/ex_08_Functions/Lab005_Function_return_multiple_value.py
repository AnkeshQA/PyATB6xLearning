def math_operations(a, b):
    return a + b, a - b, a * b, a / b

sum_addition, sum_subtraction, sum_multiplication, sum_division = math_operations(10, 5)
print("Addition:", sum_addition)
print("Subtraction:", sum_subtraction)
print("Multiplication:", sum_multiplication)
print("Division:", sum_division)

