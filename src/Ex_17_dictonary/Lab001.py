# dicti onary = {'key1': 'value1', 'key2': 'value2', 'key3': 'value3'}
# a dictionary is an unordered , mutable and indexed collection of key value pair in python
# defined by curly braces {}
# used in api automation testing to store json response
# example of dictionary
# value is mutable can be changed but key is immutable cannot be changed
my_dict = {'name': 'John', 'age': 30, 'city': 'New York'}
print("my_dict :", my_dict)
print("type of my_dict :", type(my_dict))

#another way to create dictonary using dict() function
another_dict = dict(name='Alice', age=25, city='Los Angeles')
print("another_dict :", another_dict)
print("type of another_dict :", type(another_dict))