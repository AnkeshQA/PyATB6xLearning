def mul(a,b):
    """
    This function takes two numbers as input and returns their multiplication.
    """
    return a * b
# calling the function and storing the result in a variable
Mul_l = lambda a,b : a * b
result = Mul_l(5, 10)
print("The multiplication of two numbers using lambda is:", result)
# explanation
# using lambda function to multiply two numbers
# lambda (arguments) : expression
# here, a and b are the arguments and a * b is the expression
# Output:
# The multiplication of two numbers using lambda is: 50

#lambda is used for one line liner function
